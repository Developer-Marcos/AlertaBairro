DROP TABLE IF EXISTS TB_OCORRENCIA_ABRIGO;
DROP TABLE IF EXISTS TB_OCORRENCIA;
DROP TABLE IF EXISTS TB_ABRIGO;
DROP TABLE IF EXISTS TB_CIDADAO;

CREATE TABLE TB_CIDADAO (
    ID        INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME      VARCHAR(100) NOT NULL,
    EMAIL     VARCHAR(100) NOT NULL UNIQUE,      
    TELEFONE  VARCHAR(20)  NOT NULL,
    ENDERECO  VARCHAR(150) NOT NULL,
    BAIRRO    VARCHAR(80)  NOT NULL
);

CREATE TABLE TB_OCORRENCIA (
    ID          INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO        VARCHAR(20)  NOT NULL,
    DESCRICAO   VARCHAR(300) NOT NULL,
    DATA_HORA   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    SEVERIDADE  INT          NOT NULL,
    ID_CIDADAO  INT          NOT NULL,
    CONSTRAINT CK_OCORRENCIA_TIPO CHECK (TIPO IN ('ALAGAMENTO', 'DESLIZAMENTO')),
    CONSTRAINT CK_OCORRENCIA_SEV  CHECK (SEVERIDADE BETWEEN 1 AND 5),
    CONSTRAINT FK_OCORRENCIA_CIDADAO FOREIGN KEY (ID_CIDADAO) REFERENCES TB_CIDADAO (ID)
);

CREATE TABLE TB_ABRIGO (
    ID                INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME              VARCHAR(100) NOT NULL,
    CAPACIDADE        INT          NOT NULL,
    VAGAS_DISPONIVEIS INT          NOT NULL,
    LOGRADOURO        VARCHAR(150) NOT NULL,
    BAIRRO            VARCHAR(80)  NOT NULL,
    CONSTRAINT CK_ABRIGO_CAP   CHECK (CAPACIDADE > 0),
    CONSTRAINT CK_ABRIGO_VAGAS CHECK (VAGAS_DISPONIVEIS >= 0 AND VAGAS_DISPONIVEIS <= CAPACIDADE)
);

CREATE TABLE TB_OCORRENCIA_ABRIGO (
    ID_OCORRENCIA INT NOT NULL,
    ID_ABRIGO     INT NOT NULL,
    PRIMARY KEY (ID_OCORRENCIA, ID_ABRIGO),      -- PK composta: nao repete o par
    CONSTRAINT FK_OA_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES TB_OCORRENCIA (ID),
    CONSTRAINT FK_OA_ABRIGO     FOREIGN KEY (ID_ABRIGO)     REFERENCES TB_ABRIGO (ID)
);

